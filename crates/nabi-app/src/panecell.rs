//! 화면의 한 점이 **어느 칸인가** — 픽셀에서 (행, 시각열)로 옮기는 유일한 자리.
//!
//! ## 왜 한 곳에 모으는가
//!
//! 같은 식이 다섯 파일에 아홉 벌 있었다(클릭·더블클릭·선택·링크·마우스 리포트).
//! 지금은 아홉 벌이 다 같지만, 한 벌만 고쳐지는 날 **클릭한 자리와 선택된 자리가 한 칸씩
//! 어긋난다.** 그 어긋남은 화면에서 바로 보이지 않고 "가끔 한 글자가 덜 잡힌다"로만 온다.
//!
//! ## 규칙
//!
//! * 칸의 **왼쪽 위 모서리가 그 칸에 속한다** — 경계에 정확히 찍으면 오른쪽/아래 칸이다.
//!   터미널 관행이고, 이렇게 해야 0열의 왼쪽 끝을 눌러 0열이 잡힌다.
//! * 영역 **밖 왼쪽·위는 0으로** 당긴다. 창 가장자리를 스치며 긋는 드래그가 끊기지 않는다.
//! * 글자 크기가 아직 0이면 **0칸으로 답한다.** 나누면 무한대가 되고, 그 값을 칸 번호로
//!   쓰면 마우스 리포트에 65535 같은 열이 실려 나간다.
//!
//! 오른쪽·아래 한계는 여기서 자르지 않는다 — 부르는 쪽마다 한계가 다르기 때문이다
//! (그리드는 셀 수로, 마우스 리포트는 화면 크기로 자른다).

/// 그 점이 놓인 (행, 시각열). 시각열은 **넓은 글자를 두 칸으로 센 열**이다 —
/// 셀 인덱스로 바꾸려면 `TermModel::render_index_at` 을 한 번 더 거친다.
pub(crate) fn at(rect: egui::Rect, cw: f32, ch: f32, pos: egui::Pos2) -> (usize, usize) {
    (row(rect, ch, pos.y), axis(pos.x - rect.left(), cw))
}

/// 행만 필요할 때(세 번 클릭으로 줄을 통째로 고르는 것처럼).
pub(crate) fn row(rect: egui::Rect, ch: f32, y: f32) -> usize {
    axis(y - rect.top(), ch)
}

/// 한 축 — 시작점에서 얼마나 떨어졌는가를 칸 수로.
fn axis(offset: f32, size: f32) -> usize {
    // 아직 글자 크기를 모른다. 나누면 무한대가 되고, 그 값이 칸 번호로 쓰인다.
    // NaN 은 어떤 비교에도 false 라서 `<= 0.0` 만으로는 안 걸린다 — 따로 묻는다.
    if size.is_nan() || size <= 0.0 {
        return 0;
    }
    (offset / size).floor().max(0.0) as usize
}

#[cfg(test)]
mod tests {
    use super::*;

    fn r() -> egui::Rect {
        egui::Rect::from_min_size(egui::pos2(100.0, 50.0), egui::vec2(800.0, 400.0))
    }

    #[test]
    fn 왼쪽_위_모서리는_0행_0열이다() {
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(100.0, 50.0)), (0, 0));
    }

    /// 경계에 정확히 찍으면 **다음 칸**이다 — 0열 왼쪽 끝을 눌러 0열이 잡히려면 이래야 한다.
    #[test]
    fn 경계는_다음_칸에_속한다() {
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(109.9, 50.0)).1, 0);
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(110.0, 50.0)).1, 1);
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(100.0, 69.9)).0, 0);
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(100.0, 70.0)).0, 1);
    }

    /// 영역 밖 왼쪽·위는 0으로 당긴다 — 가장자리를 스치는 드래그가 끊기지 않아야 한다.
    #[test]
    fn 밖으로_나가도_음수는_없다() {
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(0.0, 0.0)), (0, 0));
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(-9999.0, -9999.0)), (0, 0));
    }

    /// **글자 크기가 0이면 0칸이다.** 안 그러면 무한대가 되고, 그 값이 칸 번호로 쓰이면
    /// 마우스 리포트에 65535 같은 열이 실려 나간다.
    #[test]
    fn 글자_크기가_없으면_0칸() {
        assert_eq!(at(r(), 0.0, 0.0, egui::pos2(900.0, 400.0)), (0, 0));
        assert_eq!(at(r(), f32::NAN, f32::NAN, egui::pos2(900.0, 400.0)), (0, 0));
        assert_eq!(at(r(), -1.0, -1.0, egui::pos2(900.0, 400.0)), (0, 0));
    }

    #[test]
    fn 보통_자리는_그대로_센다() {
        // 왼쪽에서 255px = 25.5칸 → 25열. 위에서 205px = 10.25줄 → 10행.
        assert_eq!(at(r(), 10.0, 20.0, egui::pos2(355.0, 255.0)), (10, 25));
    }
}
