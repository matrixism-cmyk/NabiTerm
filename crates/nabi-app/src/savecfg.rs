//! 설정 저장을 **한 곳으로** 모으고, 실패하면 말한다(배치 AA).
//!
//! 설정을 저장하는 자리가 마흔두 곳이었고 전부 오류를 삼켰다 — `let _ = nabi_config::save(…)`.
//!
//! (이 설명에 그 코드를 그대로 적어 두었더니, 호출부를 일괄로 바꾸면서 **설명까지 바뀌어**
//! 무슨 말인지 알 수 없게 됐다. 그래서 지금은 글로 적는다.)
//!
//! 디스크가 차거나 설정 폴더가 읽기 전용이면 **저장이 조용히 실패한다.** 사용자는 그 자리에서
//! 아무것도 못 느끼고, 다시 켰을 때 바꿔 둔 것이 전부 돌아가 있는 것을 본다. 그때는 무엇이
//! 언제 실패했는지 알 방법이 없다.
//!
//! 이 배치가 계속 다룬 것과 같은 결함이다 — **조용한 실패**. 다만 앞의 것들이 "읽을 때"라면
//! 이건 "쓸 때"다.
//!
//! ## 왜 알림 하나로 충분한가
//!
//! 저장은 사용자가 방금 한 행동(설정 바꾸기)의 결과라, 그 자리에서 한 줄이면 알아차린다.
//! 모달로 막으면 설정을 만질 때마다 흐름이 끊긴다 — 성공이 압도적으로 흔한 일이다.

use crate::app::NabiApp;
use nabi_i18n::tr;
use std::time::Instant;

impl NabiApp {
    /// 설정을 저장하고, 실패하면 알린다. 성공하면 아무 말도 하지 않는다.
    ///
    /// 마흔두 곳에서 `let _ = nabi_config::save(...)` 로 흩어져 있던 것을 여기로 모았다.
    /// 흩어져 있으면 "이 자리만 조용히 실패해도 괜찮다"는 판단이 자리마다 달라진다.
    pub(crate) fn save_config(&mut self) {
        if let Err(e) = nabi_config::save(&self.config_path, &self.config) {
            // 원문을 함께 보여 준다 — "저장 실패"만으로는 디스크가 찬 것인지 권한 문제인지
            // 알 수 없고, 그 둘은 사용자가 할 일이 다르다.
            self.notify = Some((
                format!("{} — {e}", tr(self.lang, "cfg.savefailed")),
                Instant::now(),
            ));
        }
    }
}
