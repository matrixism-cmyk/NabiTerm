//! 셸에 넘길 글자를 **작은따옴표로 감싼다**(POSIX).
//!
//! ## 왜 한곳에 두는가
//!
//! 같은 것이 세 곳에 따로 적혀 있었다 — 원격 명령을 만드는 곳, 편집기의 변환 도구,
//! SFTP 해시 확인. 셋 다 같은 결과를 냈지만, **이런 것은 갈라지면 위험하다.**
//! 인용이 한 자리만 잘못되면 파일 이름에 든 글자가 명령으로 읽힌다.
//!
//! 이름이 구체적인데 여러 파일에 흩어져 있는 함수를 세다가 찾았다(배치 BK).
//!
//! ## 규칙
//!
//! 작은따옴표 안에서는 어떤 글자도 특별한 뜻을 갖지 않는다. 딱 하나, 작은따옴표
//! 자신만 예외라 `'\''` 로 끊어 이어 붙인다 — 따옴표를 닫고, 이스케이프한 따옴표를
//! 하나 넣고, 다시 연다.
//!
//! 윈도우 `cmd` 는 이 규칙을 따르지 않는다. 이 함수는 원격 셸(POSIX)에 넘길 때만 쓴다.

/// 셸이 통째로 한 낱말로 읽도록 감싼다.
pub fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use super::shell_quote;

    #[test]
    fn 보통_글은_그대로_감싼다() {
        assert_eq!(shell_quote("a.txt"), "'a.txt'");
        assert_eq!(shell_quote("이름 있는 파일.txt"), "'이름 있는 파일.txt'");
    }

    /// 작은따옴표가 든 이름이 이 함수의 존재 이유다.
    #[test]
    fn 작은따옴표를_끊어_잇는다() {
        assert_eq!(shell_quote("it's"), r"'it'\''s'");
    }

    /// 셸에서 뜻을 갖는 글자들이 **낱말 하나로** 묶여야 한다.
    #[test]
    fn 특수한_글자도_한_낱말이_된다() {
        for s in ["a b", "a;rm -rf /", "$(whoami)", "`id`", "a|b", "a&b", "a>b", "*"] {
            let q = shell_quote(s);
            assert!(q.starts_with('\'') && q.ends_with('\''), "{s} → {q}");
            // 안쪽에는 감싸지 않은 작은따옴표가 없어야 한다.
            assert!(!q[1..q.len() - 1].contains('\''), "{s} → {q}");
        }
    }
}
