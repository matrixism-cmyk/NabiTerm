//! 서버가 준 파일 이름을 **로컬 경로로 쓰기 전에** 거른다.
//!
//! ## 왜 필요한가
//!
//! 폴더를 통째로 내려받을 때 서버가 알려 준 이름을 그대로 로컬 경로에 이어 붙였다.
//! 그런데 그 이름은 **우리가 짓지 않는다.** 서버가 이런 이름을 돌려주면 받는 폴더를
//! 벗어난다(직접 확인한 결과다).
//!
//! ```text
//!            ..\evil.txt  ->  C:\dl\..\evil.txt        위로 올라간다
//!    C:\Windows\evil.txt  ->  C:\Windows\evil.txt      폴더를 통째로 갈아 치운다
//!                a/b.txt  ->  C:\dl\a/b.txt            안쪽으로 파고든다
//! ```
//!
//! 마지막 것은 `Path::join` 이 절대 경로를 만나면 **앞의 것을 버리기** 때문이다.
//! 고장 난 서버 하나, 또는 남의 서버에 접속하는 것만으로 임의의 자리에 파일이 써진다.
//!
//! ## 무엇을 거르는가
//!
//! 이름은 **이름이어야 한다** — 경로가 아니라. 그래서 경로가 될 수 있는 것을 다 막는다.
//! 구분자(`/` `\`), 위로 올라가는 `..`, 제자리 `.`, 드라이브 접두사(`C:`), 빈 이름, 널 문자.
//!
//! ## 가운데 콜론은 여기서 막지 않는다 (2026-08-30 통합)
//!
//! 처음에는 콜론이 **하나라도** 있으면 막았다. 그런데 리눅스에는 `2026-08-28T10:00:00.log`
//! 같은 이름이 흔하다. 그걸 "위험한 이름"으로 보고하면 사용자는 서버가 공격한다고 오해한다.
//!
//! 가운데 콜론은 폴더를 벗어나게 하지 않는다 — 윈도우가 **쓸 수 없을** 뿐이다(NTFS 는
//! 대체 데이터 스트림 문법으로 읽는다). 그건 보안이 아니라 쓸 수 있음의 문제이고,
//! `syncplan::writable_on_windows` 가 **왜 못 받는지 말해 준다.** 조용히 건너뛰는 이 함수와
//! 달리 그쪽은 이유를 알려 주므로, 두 질문을 갈라 둔 것이 사용자에게 낫다.
//!
//! 규칙은 여기 하나뿐이다. 앱 쪽 `syncplan::safe_name` 은 이 함수를 부른다 — 두 벌로 두었더니
//! 실제로 규칙이 갈렸다(한쪽은 콜론 전부 금지, 다른 쪽은 허용).
//!
//! 거른 것은 **조용히 넘기지 않는다.** 부른 쪽이 몇 개를 건너뛰었는지 알 수 있어야
//! 사용자에게 말해 줄 수 있다 — 파일이 하나 없는데 아무 말도 없으면 받은 줄 안다.

/// 이 이름을 로컬 경로 조각으로 써도 되는가.
pub fn is_safe_entry_name(name: &str) -> bool {
    !name.is_empty()
        && name != "."
        && name != ".."
        && !name.contains('/')
        && !name.contains('\\')
        // 드라이브 접두사만 막는다(`C:evil` 은 join 이 앞을 통째로 버린다).
        // 가운데 콜론은 폴더를 벗어나게 하지 않는다 — 위 설명 참고.
        && !is_drive_prefix(name)
        // 널 문자는 경로 API 가 통째로 거부하거나 잘라 버린다.
        && !name.contains('\0')
}

/// `C:` 처럼 드라이브를 가리키는 접두사인가 — 이것이 붙으면 `join` 이 앞을 버린다.
fn is_drive_prefix(name: &str) -> bool {
    let b = name.as_bytes();
    b.len() >= 2 && b[0].is_ascii_alphabetic() && b[1] == b':'
}

#[cfg(test)]
mod tests {
    use super::is_safe_entry_name;

    #[test]
    fn 보통_이름은_받는다() {
        for ok in ["a.txt", "보고서.hwp", "a b.txt", "a.tar.gz", "...hidden"] {
            assert!(is_safe_entry_name(ok), "{ok} 는 멀쩡한 이름이다");
        }
    }

    /// 받는 폴더를 벗어나게 하는 것들 — 이것이 이 함수의 존재 이유다.
    #[test]
    fn 경로가_될_수_있는_것은_막는다() {
        for bad in [
            "",
            ".",
            "..",
            "../evil",
            r"..\evil",
            "a/b",
            r"a\b",
            r"C:\Windows\evil",
            "C:evil",
            "\0",
        ] {
            assert!(!is_safe_entry_name(bad), "{bad:?} 는 막아야 한다");
        }
    }

    /// 가운데 콜론은 **보안 문제가 아니다** — 리눅스에 흔한 이름이다.
    ///
    /// 이걸 "위험한 이름"으로 보고하면 사용자는 서버가 공격한다고 오해한다.
    /// 윈도우가 못 쓰는 것은 맞지만, 그건 `writable_on_windows` 가 이유를 붙여 알려 준다.
    #[test]
    fn 가운데_콜론은_막지_않는다() {
        assert!(is_safe_entry_name("2026-08-28T10:00:00.log"));
        assert!(is_safe_entry_name("backup:daily"));
        // 다만 드라이브 접두사는 여전히 막는다 — join 이 앞을 통째로 버린다.
        assert!(!is_safe_entry_name("C:x"));
        assert!(!is_safe_entry_name("z:"));
        // **한 글자 뒤의 콜론은 드라이브다.** `a:b` 는 이름처럼 보이지만 윈도우는
        // 드라이브 `a:` 의 상대 경로로 읽는다 — 시험을 쓰다가 여기서 틀렸다.
        assert!(!is_safe_entry_name("a:b"));
    }
}
