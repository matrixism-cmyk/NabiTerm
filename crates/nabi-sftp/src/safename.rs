//! 서버가 준 파일 이름을 **로컬 경로로 쓰기 전에** 거른다.
//!
//! ## 왜 필요한가
//!
//! 폴더를 통째로 내려받을 때 서버가 알려 준 이름을 그대로 로컬 경로에 이어 붙였다.
//! 그런데 그 이름은 **우리가 짓지 않는다.** 서버가 이런 이름을 돌려주면 받는 폴더를
//! 벗어난다(직접 확인한 결과다).
//!
//! ```text
//!            ..\evil.txt  ->  C:\dl\..\evil.txt        위로 올라간다
//!    C:\Windows\evil.txt  ->  C:\Windows\evil.txt      폴더를 통째로 갈아 치운다
//!                a/b.txt  ->  C:\dl\a/b.txt            안쪽으로 파고든다
//! ```
//!
//! 마지막 것은 `Path::join` 이 절대 경로를 만나면 **앞의 것을 버리기** 때문이다.
//! 고장 난 서버 하나, 또는 남의 서버에 접속하는 것만으로 임의의 자리에 파일이 써진다.
//!
//! ## 무엇을 거르는가
//!
//! 이름은 **이름이어야 한다** — 경로가 아니라. 그래서 경로가 될 수 있는 것을 다 막는다.
//! 구분자(`/` `\`), 위로 올라가는 `..`, 제자리 `.`, 드라이브를 뜻하는 `:`, 그리고 빈 이름.
//!
//! 거른 것은 **조용히 넘기지 않는다.** 부른 쪽이 몇 개를 건너뛰었는지 알 수 있어야
//! 사용자에게 말해 줄 수 있다 — 파일이 하나 없는데 아무 말도 없으면 받은 줄 안다.

/// 이 이름을 로컬 경로 조각으로 써도 되는가.
pub fn is_safe_entry_name(name: &str) -> bool {
    !name.is_empty()
        && name != "."
        && name != ".."
        && !name.contains('/')
        && !name.contains('\\')
        && !name.contains(':')
        // 널 문자는 경로 API 가 통째로 거부하거나 잘라 버린다.
        && !name.contains('\0')
}

#[cfg(test)]
mod tests {
    use super::is_safe_entry_name;

    #[test]
    fn 보통_이름은_받는다() {
        for ok in ["a.txt", "보고서.hwp", "a b.txt", "a.tar.gz", "...hidden"] {
            assert!(is_safe_entry_name(ok), "{ok} 는 멀쩡한 이름이다");
        }
    }

    /// 받는 폴더를 벗어나게 하는 것들 — 이것이 이 함수의 존재 이유다.
    #[test]
    fn 경로가_될_수_있는_것은_막는다() {
        for bad in [
            "",
            ".",
            "..",
            "../evil",
            r"..\evil",
            "a/b",
            r"a\b",
            r"C:\Windows\evil",
            "C:evil",
            "\0",
        ] {
            assert!(!is_safe_entry_name(bad), "{bad:?} 는 막아야 한다");
        }
    }
}
